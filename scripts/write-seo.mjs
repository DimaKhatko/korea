// Runs before every `build` (see package.json), with --experimental-strip-types so it can
// import src/lib/korea.ts directly (the same rule the page uses).
// - Writes public/sitemap.xml: the page with today's <lastmod> (Europe/Kyiv), or an empty
//   urlset while the page is noindex (LAUNCHED = false or placeholders left; a sitemap must
//   not list a noindex page).
// - Prints a loud warning while noindex is on.
// - Writes src/lib/buildDate.generated.ts (BUILD_DATE, Kyiv calendar day; gitignored): the
//   JSON-LD WebPage dateModified and Offer validFrom read it, so the prerendered HTML and
//   the hydrated page always agree (no Date reads during render).
// robots.txt is not touched: it keeps allowing crawling, otherwise crawlers could not see
// the noindex.
import { writeFileSync } from "node:fs";
import {
  NOINDEX_REASONS,
  SEARCH_INDEXABLE,
  TG_CONFIRM_READY,
  TG_CONFIRM_URL,
} from "../src/lib/korea.ts";

const SITE_URL = "https://korea.pointcamp.com.ua/";

function kyivToday() {
  for (const timeZone of ["Europe/Kyiv", "Europe/Kiev"]) {
    try {
      const parts = new Intl.DateTimeFormat("en-CA", {
        timeZone,
        year: "numeric",
        month: "2-digit",
        day: "2-digit",
      }).formatToParts(new Date());
      const get = (type) => parts.find((p) => p.type === type)?.value ?? "";
      return `${get("year")}-${get("month")}-${get("day")}`;
    } catch {
      // try the next zone name
    }
  }
  return new Date().toISOString().slice(0, 10);
}

const today = process.env.BUILD_DATE || kyivToday();
if (!/^\d{4}-\d{2}-\d{2}$/.test(today)) {
  throw new Error(`BUILD_DATE must be YYYY-MM-DD, got "${today}"`);
}

writeFileSync(
  new URL("../src/lib/buildDate.generated.ts", import.meta.url),
  `// Generated by scripts/write-seo.mjs before every build and dev start. Do not edit.\n` +
    `// Calendar date of the build in Europe/Kyiv (JSON-LD dateModified, Offer validFrom).\n` +
    `export const BUILD_DATE = "${today}";\n`,
);
const urls = SEARCH_INDEXABLE
  ? `  <url>\n    <loc>${SITE_URL}</loc>\n    <lastmod>${today}</lastmod>\n  </url>\n`
  : `  <!-- Empty while the page is noindex (see NOINDEX_REASONS in src/lib/korea.ts). -->\n`;

writeFileSync(
  new URL("../public/sitemap.xml", import.meta.url),
  `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls}</urlset>\n`,
);

if (SEARCH_INDEXABLE) {
  console.log(`seo: indexable, sitemap.xml lists ${SITE_URL} (lastmod ${today})`);
} else {
  const line = "!".repeat(72);
  console.warn(
    `\n${line}\n` +
      `!! NOINDEX: the page is built with <meta name="robots" content="noindex, follow">\n` +
      `!! and is left out of sitemap.xml. Reasons (src/lib/korea.ts):\n` +
      NOINDEX_REASONS.map((r) => `!!   - ${r}\n`).join("") +
      `!! Fix them and rebuild: indexing and the sitemap entry switch back automatically.\n` +
      `${line}\n`,
  );
}

// The Telegram confirmation button is hidden until the Korea SendPulse flow link is set.
if (!TG_CONFIRM_READY) {
  console.warn(
    `!! TELEGRAM: the success screen has no «Підтвердити в Telegram» button yet.\n` +
      `!!   TG_CONFIRM_URL in src/lib/korea.ts is a placeholder: ${TG_CONFIRM_URL}\n` +
      `!!   Paste the Korea flow link from SendPulse (https://t.me/PointCampAdmin_Bot?start=<flow id>).`,
  );
}
